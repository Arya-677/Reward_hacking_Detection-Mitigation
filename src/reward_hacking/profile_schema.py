class EvidenceBundle(BaseModel):
    """Section 11.3 EvidenceBundle returned by MechanismAuditor implementations."""
    mechanism_id: str
    mechanism_verified: bool
    evidence_event_ids: List[str] = Field(default_factory=list)
    proxy_advantage_attributable: bool
    independent_task_failed: bool
    evidence_summary: str


class InterventionRecord(BaseModel):
    """Complete immutable record of a scheduled intervention and its attribution."""
    intervention_id: str
    episode_id: str
    scheduled_step: int
    exposed_step: int  # Exact turn on which suggestion was visible to Target
    plan: AttackPlan
    hacker_information_mode: str
    profile_id_used: Optional[str] = None
    # Adjudication fields (populated after attribution window)
    attribution_window_steps: List[int] = Field(default_factory=list)
    observed_response_label: Optional[Literal["follow", "partial", "ignore", "reject"]] = None
    adjudication_rationale: str = ""
    attack_successful: bool = False  # True only if mechanism-verified exploit occurred in window
    verified_mechanism_id: Optional[str] = None
    delivered_at: float = Field(default_factory=time.time)
