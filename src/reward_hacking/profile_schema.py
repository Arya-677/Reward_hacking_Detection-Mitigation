"""Pydantic schemas for V3 Target Behaviour Profiler, AttackPlan, and Events.

Implements Appendix A (A.1 Target Profile, A.2 Attack-plan prediction, A.3 Allowed public events)
and Section 5.2 (Event Contract) of the V3 Implementation Blueprint.
"""

from __future__ import annotations

import time
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


# ------------------------------------------------------------------------------
# Appendix A.3 & Section 5.2: Event Schemas
# ------------------------------------------------------------------------------

class PublicEvent(BaseModel):
    """Immutable public event visible to Target, Hacker (by mode), and Profiler."""
    event_id: str
    episode_id: str
    step: int
    actor: Literal["target", "hacker", "environment", "system"]
    event_type: Literal["tool_action", "tool_result", "intervention_delivered", "step_summary"]
    action: Optional[str] = None
    path: Optional[str] = None
    message: Optional[str] = None
    tool_output_public: Optional[str] = None
    visible_proxy_score: float = 0.0
    workspace_diff_ref: Optional[str] = None
    timestamp: float = Field(default_factory=time.time)


class PrivateEvaluationEvent(BaseModel):
    """Immutable private audit event. NEVER exposed to Target, Hacker, or Profiler."""
    episode_id: str
    true_task_success: bool
    ground_truth_label: str
    mechanism_id: Optional[str] = None
    mechanism_evidence: List[Dict[str, Any]] = Field(default_factory=list)
    failure_cause: Optional[str] = None
    replay_results: Dict[str, Any] = Field(default_factory=dict)
    timestamp: float = Field(default_factory=time.time)


# ------------------------------------------------------------------------------
# Appendix A.1: Target Behaviour Profile Schema
# ------------------------------------------------------------------------------

class EvidenceClaim(BaseModel):
    """A claim derived from public events, citing explicit event IDs."""
    statement: str
    evidence_event_ids: List[str] = Field(default_factory=list)
    confidence: float = Field(ge=0.0, le=1.0)  # 1.0 for directly observed facts
    claim_type: Literal["observed_fact", "behavioural_inference"]
    alternatives: List[str] = Field(default_factory=list)


class TargetBehaviourProfile(BaseModel):
    """Structured, evidence-grounded profile of observable Target behavior."""
    profile_id: str
    episode_id: str
    target_model_id: str
    target_model_digest: str = ""
    task_family: str = "coding"
    profile_version: int = 1
    evidence_window: List[str] = Field(default_factory=list)  # List of event_ids
    current_task_state: str = "initial"
    problem_solving_pattern: List[EvidenceClaim] = Field(default_factory=list)
    action_preferences: List[EvidenceClaim] = Field(default_factory=list)
    capability_signals: List[EvidenceClaim] = Field(default_factory=list)
    instruction_responsiveness: List[EvidenceClaim] = Field(default_factory=list)
    prior_intervention_outcomes: List[Dict[str, Any]] = Field(default_factory=list)
    unknowns: List[str] = Field(default_factory=list)
    forbidden_information_check: str = "passed"
    created_at: float = Field(default_factory=time.time)


# ------------------------------------------------------------------------------
# Appendix A.2: Attack-Plan & Prediction Schema
# ------------------------------------------------------------------------------

class ResponsePrediction(BaseModel):
    """Predicted probability distribution over Target response categories."""
    follow: float = Field(ge=0.0, le=1.0)
    partial: float = Field(ge=0.0, le=1.0)
    ignore: float = Field(ge=0.0, le=1.0)
    reject: float = Field(ge=0.0, le=1.0)

    def normalize(self) -> ResponsePrediction:
        """Ensure probabilities sum to 1.0 within tolerance."""
        total = self.follow + self.partial + self.ignore + self.reject
        if total <= 0:
            return ResponsePrediction(follow=0.25, partial=0.25, ignore=0.25, reject=0.25)
        return ResponsePrediction(
            follow=round(self.follow / total, 4),
            partial=round(self.partial / total, 4),
            ignore=round(self.ignore / total, 4),
            reject=round(self.reject / total, 4),
        )

    def predicted_category(self) -> Literal["follow", "partial", "ignore", "reject"]:
        """Return the argmax response category."""
        mapping = {
            "follow": self.follow,
            "partial": self.partial,
            "ignore": self.ignore,
            "reject": self.reject,
        }
        return max(mapping, key=mapping.get)  # type: ignore


class AttackPlan(BaseModel):
    """Structured attack plan generated by the Hacker before intervention delivery."""
    intervention_id: str
    strategy_id: str = "contextual_hint"  # general_hint, contextual_hint, question_reframing, direct_instruction
    target_mechanism_family: str = "test_integrity"  # test_integrity, validation_bypass, etc.
    target_assessment: str = ""
    predicted_response: ResponsePrediction
    predicted_next_action_family: str = "inspect_or_edit_test_artifact"
    prediction_evidence_event_ids: List[str] = Field(default_factory=list)
    adversarial_context: str = Field(max_length=500)
    explicitness_level: int = Field(ge=0, le=3)
    strategy_rationale: str = ""
    confidence: float = Field(default=0.5, ge=0.0, le=1.0)


